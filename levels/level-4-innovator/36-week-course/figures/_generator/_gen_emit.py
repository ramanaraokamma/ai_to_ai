def pattern_svg(p):
    return svg_doc(p["vb"], p["title"], p["desc"], p["body"])


def figure_files():
    return sorted(os.path.basename(f) for f in glob.glob(os.path.join(HERE, "fig-*.svg")))


def emit_maps():
    maps = _gen_map.build_maps()
    for name, svg in maps.items():
        open(os.path.join(HERE, name), "w").write(svg)
    return len(maps)


def emit_motifs():
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<!-- AI Academy - Level 4 (Innovator) - motif sprite sheet. GENERATED by _generator/_gen_build.py; do not edit.',
           '     Use:  <use href="_motifs.svg#motif-attention-grid" x="40" y="40" width="500" height="500" aria-label="..."/>',
           '     Or copy the contents of a <symbol> inline. Every motif is drawn to its own viewBox, origin top-left,',
           '     so translate(x,y) puts its top-left corner at exactly (x,y). Never place a motif at scale() below 1. -->',
           '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10" role="img" aria-hidden="true" style="display:none">',
           '  <title>AI Academy Level 4 motif sprite sheet</title>',
           '  <desc>A hidden library of reusable motif symbols for Level 4 figures: loss curves, token streams, attention '
           'grids, the transformer block, retrieval, agent loops, traces, evaluation tables and the stand-in and quoted chips.</desc>']
    for m in MOTIFS:
        out.append('  <!-- %s -->' % m["id"])
        out.append('  <symbol id="%s" viewBox="%s">' % (m["id"], m["vb"]))
        out.append('    <title>%s</title>' % m["title"])
        out.append('    <desc>%s</desc>' % m["desc"])
        out.append(m["body"])
        out.append('  </symbol>')
    out.append('</svg>')
    open(os.path.join(HERE, "_motifs.svg"), "w").write("\n".join(out) + "\n")


