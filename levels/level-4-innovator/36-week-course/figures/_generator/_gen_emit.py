def _fig(m):
    return ('<figure><svg viewBox="%s" role="img" aria-label="%s"><use href="#%s"/></svg>'
            '<figcaption><code>%s</code><span>%s</span><span>%s</span></figcaption></figure>'
            % (m["vb"], m["title"], m["id"], m["id"], m["vb"], m["note"]))


def emit_preview():
    o = ['<!DOCTYPE html>',
         '<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">',
         '<title>AI Academy - Level 4 figure style system</title>', '<style>', CSS, '</style></head>', '<body>']
    sprite = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">']
    for m in MOTIFS:
        sprite.append('<symbol id="%s" viewBox="%s"><title>%s</title><desc>%s</desc>%s</symbol>'
                      % (m["id"], m["vb"], m["title"], m["desc"], m["body"]))
    sprite.append('</svg>')
    o.append("".join(sprite))
    o += ['<div class="wrap">',
          '<h1>AI Academy &mdash; Level 4 (Innovator) figure style system</h1>',
          '<p class="lead">Generated by <code>_generator/_gen_build.py</code>. Same palette, strokes, type scale and '
          'accessibility rules as Levels 1&ndash;3, plus the Level 4 rules: seeded numbers only, stand-ins drawn as '
          'stand-ins, quoted is not measured, series told apart by more than colour, heatmap cells carry their value.</p>',
          '<div class="bar">',
          '  <label><input type="checkbox" onchange="document.body.classList.toggle(\'grey\',this.checked)"> Greyscale (print check)</label>',
          '  <label><input type="checkbox" onchange="document.body.classList.toggle(\'dark\',this.checked)"> Dark page (transparency check)</label>',
          '</div>',
          '<h2>Palette &mdash; inherited verbatim</h2>', '<div class="swatches">']
    for name, s, f, aa, gs, gf in PALETTE:
        o.append('<div class="sw"><div class="chip" style="background:%s;border-color:%s"></div>' % (f or s, s))
        extra = " &middot; fill grey %s" % gf if gf else ""
        o.append('<b>%s</b><code>%s</code><span>AA %s &middot; stroke grey %s%s</span>' % (name, s, aa, gs, extra))
        o.append('<code>%s</code></div>' % f if f else '</div>')
    o.append('</div>')
    o.append('<h2>Motifs (%d)</h2>' % len(MOTIFS))
    o.append('<p class="lead">Rendered through <code>&lt;use href="#motif-id"/&gt;</code> from the inlined sprite.</p>')
    seen = set()
    for gname, ids in GROUPS:
        o.append('<h4>%s</h4><div class="motifs">' % gname)
        for mid in ids:
            o.append(_fig(BY_ID[mid]))
            seen.add(mid)
        o.append('</div>')
    assert seen == set(BY_ID), "preview groups miss motifs: %s" % sorted(set(BY_ID) - seen)
    o.append('<h2>Composition patterns (%d)</h2>' % len(PATTERNS))
    for p in PATTERNS:
        w = p["vb"].split()[2]
        o.append('<section class="pat"><h3>%s <span>%s</span></h3><p class="note">%s</p>' % (p["id"], p["vb"], p["note"]))
        o.append('<div class="frame" style="max-width:%spx"><svg viewBox="%s" role="img"><title>%s</title><desc>%s</desc>\n%s\n</svg></div></section>'
                 % (w, p["vb"], p["title"], p["desc"], p["body"]))
    files = figure_files()
    o.append('<h2>Week figures (%d fig-*.svg files)</h2>' % len(files))
    o.append('<p class="lead">Every <code>fig-*.svg</code> in this folder, shown through <code>&lt;img&gt;</code>. '
             'Reload after running <code>python3 _gen_build.py</code>.</p><div class="figs">')
    for f in files:
        o.append('<figure><img src="%s" alt="%s"><figcaption><code>%s</code></figcaption></figure>' % (f, f, f))
    o.append('</div></div></body></html>')
    open(os.path.join(HERE, "_preview.html"), "w").write("\n".join(o) + "\n")
